val DarkBackground = Color(0xFF090D1A)
val SurfaceDark = Color(0xFF10172A)
val CardBorder = Color(0xFF1E293B)
val ElectricBlue = Color(0xFF0066FF)
val ElectricBlueLight = Color(0xFF38BDF8)
val AccentGreen = Color(0xFF10B981)
val TextPrimary = Color(0xFFF1F5F9)
val TextSecondary = Color(0xFF94A3B8)

class MainActivity : ComponentActivity() {
    private lateinit var prefs: PreferencesManager

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        prefs = PreferencesManager(this)

        setContent {
            MaterialTheme(
                colorScheme = darkColorScheme(
                    primary = ElectricBlue,
                    background = DarkBackground,
                    surface = SurfaceDark
                )
            ) {
                MainDashboardScreen(prefs = prefs)
            }
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun MainDashboardScreen(prefs: PreferencesManager) {
    val context = LocalContext.current

    var hasOverlayPermission by remember { mutableStateOf(Settings.canDrawOverlays(context)) }
    var isAccessibilityActive by remember { mutableStateOf(QuickNameAccessibilityService.isServiceRunning) }
    var isFloatingServiceRunning by remember { mutableStateOf(FloatingButtonService.isRunning) }

    var totalGenerated by remember { mutableIntStateOf(prefs.totalGeneratedCount) }
    var historyList by remember { mutableStateOf(prefs.getHistory()) }
    var enableFirst by remember { mutableStateOf(prefs.enableFirstName) }
    var enableLast by remember { mutableStateOf(prefs.enableLastName) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(
                            modifier = Modifier
                                .size(36.dp)
                                .clip(CircleShape)
                                .background(Brush.linearGradient(listOf(ElectricBlue, ElectricBlueLight))),
                            contentAlignment = Alignment.Center
                        ) {
                            Text("QN", color = Color.White, fontWeight = FontWeight.Bold, fontSize = 14.sp)
                        }
                        Spacer(modifier = Modifier.width(12.dp))
                        Text("QuickName AutoFill", fontWeight = FontWeight.Bold, color = TextPrimary)
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = DarkBackground)
            )
        },
        containerColor = DarkBackground
    ) { padding ->
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(horizontal = 16.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            item {
                Text("Permissions", fontWeight = FontWeight.SemiBold, fontSize = 14.sp, color = ElectricBlueLight)
                Spacer(modifier = Modifier.height(6.dp))
                PermissionCard(
                    title = "Display Over Other Apps",
                    isGranted = hasOverlayPermission,
                    onAction = {
                        val intent = Intent(Settings.ACTION_MANAGE_OVERLAY_PERMISSION, Uri.parse("package:${context.packageName}"))
                        context.startActivity(intent)
                    }
                )
            }

            item {
                PermissionCard(
                    title = "Accessibility AutoFill",
                    isGranted = isAccessibilityActive,
                    onAction = {
                        val intent = Intent(Settings.ACTION_ACCESSIBILITY_SETTINGS)
                        context.startActivity(intent)
                    }
                )
            }

            item {
                Text("Overlay Controller", fontWeight = FontWeight.SemiBold, fontSize = 14.sp, color = ElectricBlueLight)
                Spacer(modifier = Modifier.height(6.dp))
                Card(
                    colors = CardDefaults.cardColors(containerColor = SurfaceDark),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier.border(1.dp, CardBorder, RoundedCornerShape(12.dp))
                ) {
                    Row(
                        modifier = Modifier.padding(16.dp).fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Text(if (isFloatingServiceRunning) "Overlay Running" else "Overlay Stopped", color = TextPrimary)
                        Button(
                            onClick = {
                                if (!hasOverlayPermission) {
                                    val intent = Intent(Settings.ACTION_MANAGE_OVERLAY_PERMISSION, Uri.parse("package:${context.packageName}"))
                                    context.startActivity(intent)
                                    return@Button
                                }
                                val serviceIntent = Intent(context, FloatingButtonService::class.java)
                                if (isFloatingServiceRunning) {
                                    context.stopService(serviceIntent)
                                    isFloatingServiceRunning = false
                                } else {
                                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                                        context.startForegroundService(serviceIntent)
                                    } else {
                                        context.startService(serviceIntent)
                                    }
                                    isFloatingServiceRunning = true
                                }
                            },
                            colors = ButtonDefaults.buttonColors(containerColor = if (isFloatingServiceRunning) Color(0xFFEF4444) else ElectricBlue)
                        ) {
                            Text(if (isFloatingServiceRunning) "Stop" else "Start")
                        }
                    }
                }
            }

            item {
                Text("Configuration", fontWeight = FontWeight.SemiBold, fontSize = 14.sp, color = ElectricBlueLight)
                Card(
                    colors = CardDefaults.cardColors(containerColor = SurfaceDark),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier.border(1.dp, CardBorder, RoundedCornerShape(12.dp))
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                            Text("Total Generated", color = TextSecondary)
                            Text("$totalGenerated", fontWeight = FontWeight.Bold, color = ElectricBlueLight)
                        }
                        Divider(modifier = Modifier.padding(vertical = 10.dp), color = CardBorder)
                        Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                            Text("First Name", color = TextPrimary)
                            Switch(checked = enableFirst, onCheckedChange = { enableFirst = it; prefs.enableFirstName = it })
                        }
                        Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                            Text("Last Name", color = TextPrimary)
                            Switch(checked = enableLast, onCheckedChange = { enableLast = it; prefs.enableLastName = it })
                        }
                    }
                }
            }

            item {
                Text("Recent Names", fontWeight = FontWeight.SemiBold, fontSize = 14.sp, color = ElectricBlueLight)
            }

            items(historyList) { name ->
                Card(
                    colors = CardDefaults.cardColors(containerColor = SurfaceDark),
                    shape = RoundedCornerShape(10.dp),
                    modifier = Modifier.fillMaxWidth().border(1.dp, CardBorder, RoundedCornerShape(10.dp))
                ) {
                    Row(modifier = Modifier.padding(14.dp).fillMaxWidth()) {
                        Text(name, color = TextPrimary, fontWeight = FontWeight.Medium)
                    }
                }
            }
        }
    }
}

@Composable
fun PermissionCard(title: String, isGranted: Boolean, onAction: () -> Unit) {
    Card(
        colors = CardDefaults.cardColors(containerColor = SurfaceDark),
        shape = RoundedCornerShape(12.dp),
        modifier = Modifier.fillMaxWidth().border(1.dp, CardBorder, RoundedCornerShape(12.dp))
    ) {
        Row(
            modifier = Modifier.padding(14.dp).fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            Text(title, fontWeight = FontWeight.Bold, color = TextPrimary)
            if (isGranted) {
                Icon(Icons.Default.CheckCircle, contentDescription = null, tint = AccentGreen)
            } else {
                Button(onClick = onAction, colors = ButtonDefaults.buttonColors(containerColor = ElectricBlue)) {
                    Text("Grant", fontSize = 12.sp)
                }
            }
        }
    }
}
